#!/usr/bin/env python3
"""Generate Android resources and the legacy-message catalog; --check detects drift."""
import json,re,pathlib,sys,xml.etree.ElementTree as ET
ROOT=pathlib.Path(__file__).resolve().parents[1]
rows=json.loads((ROOT/'tools/ui_translations.json').read_text())
assert len({r['key'] for r in rows})==len(rows)
assert len({r['zh'] for r in rows})==len(rows)
placeholder=re.compile(r'%[1-9][0-9]*\$s')
def kt(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$')
def android(s):
 return s.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n').replace('\t','\\t')
files={}
for lang,folder in [('zh','values'),('en','values-en'),('id','values-in')]:
 root=ET.Element('resources')
 for row in rows:
  assert row[lang].strip(),row['key']
  assert sorted(placeholder.findall(row[lang]))==sorted(placeholder.findall(row['zh'])),row['key']
  node=ET.SubElement(root,'string',{'name':row['key']})
  if not placeholder.search(row[lang]) and '%' in row[lang]:node.set('formatted','false')
  node.text=android(row[lang])
 ET.indent(root,space='    ')
 files[ROOT/f'app/src/main/res/{folder}/strings.xml']='<?xml version="1.0" encoding="utf-8"?>\n'+ET.tostring(root,encoding='unicode')+'\n'
lines=['// Generated by tools/generate_localizations.py; edit tools/ui_translations.json.','package tw.language.listener.i18n','','import tw.language.listener.R','','internal object MessageCatalog {','    val entries: Map<String, Int> = linkedMapOf(']
lines+=['        '+kt(r['zh'])+' to R.string.'+r['key']+',' for r in rows]
lines+=['    )','}','']
files[ROOT/'app/src/main/java/tw/language/listener/i18n/MessageCatalog.kt']='\n'.join(lines)
errors=[]
for p,content in files.items():
 if '--check' in sys.argv:
  if not p.exists() or p.read_text()!=content:errors.append(str(p.relative_to(ROOT)))
 else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(content)
if errors:raise SystemExit('Generated localization files need updating: '+', '.join(errors))
print(('Checked' if '--check' in sys.argv else 'Generated')+f' {len(rows)} messages in 3 languages')
